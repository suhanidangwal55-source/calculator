# ----------Simple basic calculator--------------
print(""" '+'  Addition
'-' subtraction
'*' multiplication
'/' division
""")
while True:
  opr = input("enter the operator")
  if opr in "+-*/":
     num1 = int(input("enter the number"))
     num2 = int(input("enter the number"))
     if opr == '+':
        sum = num1 + num2
        print(sum)
     elif opr == '-':
        subtract = num1 - num2
        print(subtract)
     elif opr == '*':
        multi = num1 * num2
        print(multi)
     elif opr == '/':
        div = num1/num2
        print(div)
  else:
    print("enter the valid operator")
    break

